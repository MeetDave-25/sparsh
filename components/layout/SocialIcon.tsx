function platform(label: string, url: string) {
  const s = `${label} ${url}`.toLowerCase();
  if (s.includes('instagram')) return 'instagram';
  if (s.includes('facebook') || s.includes('fb.com')) return 'facebook';
  if (s.includes('youtube') || s.includes('youtu.be')) return 'youtube';
  if (s.includes('pinterest')) return 'pinterest';
  if (s.includes('linkedin')) return 'linkedin';
  if (s.includes('whatsapp') || s.includes('wa.me')) return 'whatsapp';
  if (s.includes('twitter') || s.includes('x.com')) return 'x';
  return null;
}

/** Brand icon for a social profile link, guessed from its name or URL; a globe otherwise. */
export default function SocialIcon({ label, url, size = 18 }: { label: string; url: string; size?: number }) {
  const key = platform(label, url);
  if (!key) return <Globe size={size} />;
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
      <path d={PATHS[key]} />
    </svg>
  );
}
